    #[test]
    fn a_biped_gets_two_antiphase_legs_and_counter_swinging_arms() {
        let rig = biped();
        let set = build_locomotion(BodyPlan::Biped, &rig, &GaitParams::default()).unwrap();
        assert_eq!(set.legs.len(), 2);
        assert_eq!(set.legs[0].phase, 0.0);
        assert_eq!(set.legs[1].phase, 0.5);

        // hips + (upper, lower) × 2 legs + 2 arms.
        assert_eq!(set.walk.tracks.len(), 1 + 4 + 2);
        let arm = rig.skeleton.index_of("upper_arm_l").unwrap();
        let leg = rig.skeleton.index_of("upper_leg_l").unwrap();
        let arm_track = set.walk.tracks.iter().find(|t| t.joint == arm).unwrap();
        let leg_track = set.walk.tracks.iter().find(|t| t.joint == leg).unwrap();
        // A quarter of the way through the cycle both are at their extreme, and
        // the extremes are opposite: `x` carries the whole rotation here.
        let q = |t: &JointTrack, i: usize| t.rotation.as_ref().unwrap().values[i][0];
        let k = (GaitParams::default().keys_per_cycle / 4) as usize;
        assert!(
            q(arm_track, k) * q(leg_track, k) < 0.0,
            "the arm and the leg on the same side swing the same way: arm {}, leg {}",
            q(arm_track, k),
            q(leg_track, k)
        );
    }

