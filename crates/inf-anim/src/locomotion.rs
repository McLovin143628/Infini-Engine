    /// The machine actually walks its states when `speed` moves — the property
    /// the wizard's whole "wired to a state machine" claim rests on, checked
    /// against the real evaluator rather than by reading the table.
    #[test]
    fn the_generated_machine_climbs_and_falls_with_speed() {
        let rig = biped();
        let set = build_locomotion(BodyPlan::Biped, &rig, &GaitParams::default()).unwrap();
        let sm = locomotion_machine(&set, [1; 16], [2; 16], [3; 16]);
        let mut rt = crate::state_machine::SmRuntime::default();
        let dt = 1.0 / 60.0;

        let drive = |speed: f64, steps: usize, rt: &mut crate::state_machine::SmRuntime| {
            let lookup = |name: &str| (name == SPEED_VAR).then_some(speed);
            let ctx = crate::state_machine::SmContext::new(&lookup);
            for _ in 0..steps {
                rt.advance(&sm, &ctx, dt);
            }
        };

        drive(0.0, 4, &mut rt);
        assert_eq!(rt.current, 0, "a stationary character idles");
        drive(set.walk_speed_m_s, 4, &mut rt);
        assert_eq!(rt.current, 1, "at the walk cycle's own speed it walks");
        drive(set.run_speed_m_s, 4, &mut rt);
        assert_eq!(rt.current, 2, "at the run cycle's own speed it runs");
        drive(0.0, 8, &mut rt);
        assert_eq!(rt.current, 0, "and it comes all the way back down");
    }

