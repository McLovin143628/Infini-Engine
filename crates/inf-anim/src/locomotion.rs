    /// **The knee never leaves the half of its hinge the rig authorizes.**
    ///
    /// The clip is not run through the IK clamp — nothing solves a clip — so this
    /// is the only thing between an ambitious `knee_flex_deg` and committed
    /// content in which a knee bends backwards.
    #[test]
    fn the_knee_flexes_only_the_way_its_limit_allows() {
        let rig = biped();
        let gait = GaitParams {
            // Far past the −150° the template's hinge permits, and past 180°
            // where the half-angle sine changes sign.
            knee_flex_deg: 400.0,
            ..GaitParams::default()
        };
        let set = build_locomotion(BodyPlan::Biped, &rig, &gait).unwrap();
        let knee = rig.skeleton.index_of("lower_leg_l").unwrap();
        let track = set.walk.tracks.iter().find(|t| t.joint == knee).unwrap();
        let ceiling = knee_flex_ceiling(
            &rig,
            &legs_of(BodyPlan::Biped, &rig, &bind_globals(&rig.skeleton)).unwrap(),
        );
        assert_eq!(ceiling, Some(150.0), "the template's own hinge");
        for v in &track.rotation.as_ref().unwrap().values {
            // A negative rotation about X has a non-positive `x` component for
            // any angle in (−180°, 0].
            assert!(
                v[0] <= 1.0e-6,
                "a knee key rotates the wrong way about X: {v:?}"
            );
            // …and it never exceeds the authorized magnitude.
            let half = 150f64.to_radians() * 0.5;
            assert!(
                (v[0] as f64) >= -psin64(half) - 1.0e-6,
                "a knee key flexes past the rig's own limit: {v:?}"
            );
        }
    }

    /// **The bound `knee_flex_ceiling` documents, measured.**
    ///
    /// A knee whose authored range is entirely positive — an inverted hinge, which
    /// only the Skeleton Editor can produce — walks with a straight knee, because
    /// the flex direction is fixed negative. Asserted as it is, so the day the
    /// generator learns to sign the flex from the limit this test fails and the
    /// paragraph on `knee_flex_ceiling` gets rewritten rather than forgotten.
    #[test]
    fn an_inverted_knee_hinge_walks_stiff_legged_and_that_is_ledgered() {
        let mut rig = biped();
        let knees: Vec<u16> = rig
            .skeleton
            .joints()
            .iter()
            .enumerate()
            .filter(|(_, j)| j.name.starts_with("lower_leg_"))
            .map(|(i, _)| i as u16)
            .collect();
        assert_eq!(knees.len(), 2, "the fixture must have knees to invert");
        for limit in &mut rig.limits {
            if knees.contains(&limit.joint) {
                // The same range, the other way round.
                *limit = crate::template::JointLimit::hinge_x(limit.joint, 0.0, 150.0);
            }
        }
        let set = build_locomotion(BodyPlan::Biped, &rig, &GaitParams::default()).unwrap();
        for knee in knees {
            let track = set.walk.tracks.iter().find(|t| t.joint == knee).unwrap();
            let rot = track.rotation.as_ref().unwrap();
            // Every key is the same rotation, and that rotation is (numerically)
            // the identity. Not `== [0,0,0,1]`: `pcos64(0)` is 0.999_999_94, which
            // is the polynomial's documented ~1e-7 and what every key in every
            // generated clip carries — `QuatTrack::sample` normalizes.
            assert!(
                rot.values.iter().all(|v| v[0].abs() < 1.0e-6
                    && v[1] == 0.0
                    && v[2] == 0.0
                    && (v[3] - 1.0).abs() < 1.0e-6),
                "the knee moved; the generator now signs the flex from the limit — \
                 delete this test and rewrite `knee_flex_ceiling`'s bound paragraph"
            );
        }
        // …and the hips still swing, so the straight knee is the *limit's* doing
        // and not a clip that came out empty.
        let hip = rig.skeleton.index_of("upper_leg_l").unwrap();
        let hip_track = set.walk.tracks.iter().find(|t| t.joint == hip).unwrap();
        assert!(
            hip_track
                .rotation
                .as_ref()
                .unwrap()
                .values
                .iter()
                .any(|v| v[0] != 0.0),
            "the whole walk is inert — this arm is measuring an empty clip"
        );
    }

    /// **Byte-reproducible**, which is what the module docs claim and a stronger
    /// property than `PartialEq` can see.
    ///
    /// `assert_eq!` on an `AnimClip` compares `f32`s, and `-0.0 == 0.0` is *true*
    /// while their bytes differ — so a generator that flipped a zero's sign on
    /// alternate runs would satisfy a structural comparison and write two
    /// different `.inf_anim` files. These keyframes go on disk, into a cook and
    /// into a pack, so the claim has to be measured on
    /// [`inf_asset::encode`] — the same door
    /// `AssetProject::write_asset` puts them through, and the same shape
    /// [`crate::template`]'s `the_same_params_generate_the_same_bytes` uses.
    #[test]
    fn the_same_rig_generates_the_same_clips() {
        let rig = biped();
        let a = build_locomotion(BodyPlan::Biped, &rig, &GaitParams::default()).unwrap();
        let b = build_locomotion(BodyPlan::Biped, &rig, &GaitParams::default()).unwrap();
        assert_eq!(a, b);

        let bytes = |set: &LocomotionSet| -> Vec<Vec<u8>> {
            [&set.idle, &set.walk, &set.run]
                .iter()
                .map(|c| {
                    inf_asset::encode(&crate::asset::AnimClipAsset::new((*c).clone(), None))
                        .unwrap()
                })
                .collect()
        };
        assert_eq!(bytes(&a), bytes(&b), "a generated clip is not byte-stable");

        // …and the comparison is a filter rather than a formality: a different
        // rig writes different bytes. Without this the assertion above would pass
        // for a generator that emitted the same three clips for everything.
        let tall = build_template(
            BodyPlan::Biped,
            &BodyParams {
                height_m: 2.4,
                ..BodyParams::default()
            },
        )
        .unwrap();
        let c = build_locomotion(BodyPlan::Biped, &tall, &GaitParams::default()).unwrap();
        assert_ne!(bytes(&a), bytes(&c));

        // **And the two comparisons really are different checks.** Written out
        // rather than asserted about the generator, because the whole point is
        // that no generated value has to have this shape for the structural
        // comparison to be the weaker one.
        let key = |x: f32| {
            AnimClip::new(
                "k",
                vec![JointTrack {
                    rotation: Some(QuatTrack::new(
                        vec![0.0],
                        vec![[x, 0.0, 0.0, 1.0]],
                        Interpolation::Linear,
                    )),
                    ..JointTrack::new(0)
                }],
            )
        };
        let (plus, minus) = (key(0.0), key(-0.0));
        assert_eq!(plus, minus, "`-0.0 == 0.0`, which is the whole problem");
        assert_ne!(
            inf_asset::encode(&crate::asset::AnimClipAsset::new(plus, None)).unwrap(),
            inf_asset::encode(&crate::asset::AnimClipAsset::new(minus, None)).unwrap(),
            "the byte comparison above adds nothing over `PartialEq`"
        );
    }

